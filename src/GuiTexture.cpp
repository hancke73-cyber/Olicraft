std::vector<uint8_t> generateGuiPixels() {
    std::vector<uint8_t> px(static_cast<size_t>(GUI_TEX_W) * GUI_TEX_H * 4, 0);
    for (int c = 32; c < 127; ++c) {
        GuiRect r = glyphRect(static_cast<unsigned char>(c));
        const uint8_t* cols = FONT5X7[c - 32];
        for (int cx = 0; cx < 5; ++cx)
            for (int cy = 0; cy < 8; ++cy)
                if (cols[cx] & (1 << cy)) putPixel(px, r.x + cx, r.y + cy, 255, 255, 255, 255);
    }
    drawHeart(px, iconHeartEmpty().x, 0);
    drawHeart(px, iconHeartFull().x, 1);
    drawHeart(px, iconHeartHalf().x, 2);
    {
        const GuiRect r = iconBubble();
        for (int y = 0; y < 9; ++y)
            for (int x = 0; x < 9; ++x) {
                bool edge = BUBBLE_PATTERN[y][x] == '#';
                bool inside = false;
                if (!edge) {
                    // innen = zwischen den Raendern der Zeile
                    int l = -1, rr = -1;
                    for (int k = 0; k < 9; ++k)
                        if (BUBBLE_PATTERN[y][k] == '#') {
                            if (l < 0) l = k;
                            rr = k;
                        }
                    inside = l >= 0 && x > l && x < rr;
                    if (y == 0 || y == 8) inside = false;
                }
                if (edge) putPixel(px, r.x + x, r.y + y, 190, 225, 255, 255);
                else if (inside) putPixel(px, r.x + x, r.y + y, 70, 120, 220, 170);
            }
        putPixel(px, r.x + 2, r.y + 2, 255, 255, 255, 255);
    }
    return px;
}

GuiRect glyphRect(unsigned char c) {
    if (c < 32 || c > 126) c = '?';
    int idx = c - 32;
    return {(idx % 32) * 8, (idx / 32) * 8, GLYPH_W, GLYPH_H};
}

GuiRect iconHeartEmpty() { return {0, ICON_Y, 9, 8}; }
GuiRect iconHeartFull() { return {10, ICON_Y, 9, 8}; }
GuiRect iconHeartHalf() { return {20, ICON_Y, 9, 8}; }
GuiRect iconBubble() { return {30, ICON_Y, 9, 9}; }

int textWidthPx(const std::string& s) {
    if (s.empty()) return 0;
    return static_cast<int>(s.size()) * GLYPH_ADVANCE - (GLYPH_ADVANCE - GLYPH_W);
}

