const char* HEART_PATTERN[8] = {
    ".##...##.", "#########", "#########", "#########", ".#######.", "..#####..", "...###...", "....#....",
};

const char* BUBBLE_PATTERN[9] = {
    "..#####..", ".#.....#.", "#.......#", "#.......#", "#.......#", "#.......#", "#.......#", ".#.....#.", "..#####..",
};

constexpr int ICON_Y = 32;

void putPixel(std::vector<uint8_t>& px, int x, int y, int r, int g, int b, int a) {
    size_t i = (static_cast<size_t>(y) * GUI_TEX_W + x) * 4;
    px[i + 0] = static_cast<uint8_t>(r);
    px[i + 1] = static_cast<uint8_t>(g);
    px[i + 2] = static_cast<uint8_t>(b);
    px[i + 3] = static_cast<uint8_t>(a);
}

// Herz in Zelle ox: part 0 = leer, 1 = voll, 2 = halb (linke Haelfte gefuellt)
void drawHeart(std::vector<uint8_t>& px, int ox, int part) {
    auto solid = [&](int x, int y) {
        return x >= 0 && x < 9 && y >= 0 && y < 8 && HEART_PATTERN[y][x] == '#';
    };
    for (int y = 0; y < 8; ++y)
        for (int x = 0; x < 9; ++x) {
            if (!solid(x, y)) continue;
            bool edge = !solid(x - 1, y) || !solid(x + 1, y) || !solid(x, y - 1) || !solid(x, y + 1);
            bool filled = part == 1 || (part == 2 && x < 5);
            int r, g, b;
            if (edge) {
                r = 70; g = 8; b = 8;
            } else if (filled) {
                r = 220; g = 36; b = 40;
                if ((x == 1 || x == 2) && y == 1) { r = 255; g = 150; b = 150; }
            } else {
                r = 52; g = 38; b = 38;
            }
            putPixel(px, ox + x, ICON_Y + y, r, g, b, 255);
        }
}

